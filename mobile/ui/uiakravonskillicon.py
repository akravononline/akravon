def GetIcon(skillIndex, grade):
	import uiAkravonActionIcon
	supportIcon = uiAkravonActionIcon.GetSupportIcon(skillIndex)
	if supportIcon:
		return supportIcon
	base = TABLE.get(skillIndex)
	if not base:
		return None
	for name in (base + "_%02d" % (min(max(grade, 0), 3) + 1), base + "_01", base):
		if name in MADE:
			return "d:/ymir work/ui/akravon_skill/%s.png" % name
	return None
